"""Regenerate public contracts from immutable upstream inputs; --check never edits them."""
import argparse
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]


def fetch_input(item, manifest, destination):
    name, expected = item
    if Path(name).is_absolute() or '..' in Path(name).parts:
        raise ValueError('unsafe input path')
    url = (f"https://raw.githubusercontent.com/{manifest['repository']}/"
           f"{manifest['commit']}/{manifest['sourcePath']}/{name}")
    with urllib.request.urlopen(url, timeout=30) as response:
        data = response.read(8 * 1024 * 1024 + 1)
    if hashlib.sha256(data).hexdigest() != expected['sha256']:
        raise ValueError(f'upstream checksum mismatch: {name}')
    if name.endswith('.proto'):
        package = re.search(rb'^package ([^;]+);', data, re.M)
        if not package or package.group(1).decode() != expected['package']:
            raise ValueError(f'upstream package mismatch: {name}')
    target = destination / name
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)


def generate(staging, manifest):
    if not re.fullmatch(r'[0-9a-f]{40}', manifest['commit']):
        raise ValueError('source must be pinned to a full commit')
    tools = manifest['tools']
    version = subprocess.check_output(['buf', '--version'], text=True).strip()
    if version != tools['buf']:
        raise ValueError(f"buf {tools['buf']} required; found {version}")
    inputs = staging / 'proto'
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        list(pool.map(lambda item: fetch_input(item, manifest, inputs), manifest['files'].items()))
    env = os.environ.copy()
    env.update(GOBIN=str(staging / 'bin'), GOWORK='off', GOTOOLCHAIN='local')
    for module, tool in [('google.golang.org/protobuf', 'protoc-gen-go'),
                         ('google.golang.org/grpc/cmd/protoc-gen-go-grpc', 'protoc-gen-go-grpc')]:
        package = module + '/cmd/' + tool if tool == 'protoc-gen-go' else module
        subprocess.run(['go', 'install', f"{package}@v{tools[tool]}"], env=env, check=True, cwd=ROOT)
    env['PATH'] = env['GOBIN'] + os.pathsep + env['PATH']
    shutil.copyfile(ROOT / 'buf.yaml', staging / 'buf.yaml')
    shutil.copyfile(ROOT / 'buf.gen.yaml', staging / 'buf.gen.yaml')
    subprocess.run(['buf', 'generate'], cwd=staging, env=env, check=True)
    shutil.copyfile(inputs / 'chronicle.desc', staging / 'contracts/chronicle.desc')
    provenance = ("// Code generated by scripts/generate-contracts.py. DO NOT EDIT.\n"
                  "// Copyright (c) Cratis. All rights reserved.\n"
                  "// Licensed under the MIT license. See LICENSE file in the project root for full license information.\n\n"
                  "package contracts\n\n"
                  f"// ProtocolVersion is the upstream Chronicle release.\nconst ProtocolVersion = {json.dumps(manifest['version'])}\n\n"
                  f"// ProtocolCommit is the immutable schema source revision.\nconst ProtocolCommit = {json.dumps(manifest['commit'])}\n")
    (staging / 'contracts/provenance.go').write_text(provenance)


def owned_files(directory):
    return {p.relative_to(directory) for p in directory.rglob('*.pb.go')} | {
        Path('chronicle.desc'), Path('provenance.go')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare without changing generated files')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'contracts-source.json').read_text())
    work = ROOT / '.ai-work/contracts-generation'
    work.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=work) as temporary:
        staging = Path(temporary)
        generate(staging, manifest)
        output, target = staging / 'contracts', ROOT / 'contracts'
        new, old = owned_files(output), owned_files(target)
        changed = sorted(path for path in new | old if not (output / path).exists()
                         or not (target / path).exists()
                         or (output / path).read_bytes() != (target / path).read_bytes())
        if args.check:
            if changed:
                raise SystemExit('Contracts are out of date:\n' + '\n'.join(map(str, changed)))
            print('Contracts match the pinned source (including generated file inventory).')
            return
        for path in old - new:
            (target / path).unlink()
        for path in new:
            (target / path).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(output / path, target / path)
        print(f'Generated {len(new)} files for Chronicle {manifest["version"]}.')


if __name__ == '__main__':
    main()
